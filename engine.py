# ------------------------------------------------------------------
# Language detection
# ------------------------------------------------------------------
def detect_lang(text):
    """Return 'te', 'hi' or 'en' based on script / common words."""
    if re.search(r"[\u0C00-\u0C7F]", text):
        return "te"
    if re.search(r"[\u0900-\u097F]", text):
        return "hi"
    en_words = ("what|why|how|when|fever|pain|head|sugar|medicine|"
                "help|i |my |is |can |should")
    if re.search(en_words, text.lower()):
        return "en"
    return "te"  # default audience is Telugu-speaking rural AP

